-- 시각은 timestamptz (UTC). 확장 설치 없음 — 한국어는 모듈이 만든 2글자 조각을 tsvector('simple') 에 넣는다.

-- 색인 문서 한 줄 = 문서 하나 (doc_type, doc_id). title · body 는 NFKC 정규화한 원문(표시 · 발췌용), terms 는 조각 (title 가중 A, body 가중 B)
create table if not exists search_documents (
    id                bigint generated by default as identity primary key,
    doc_type          varchar(32)  not null,
    doc_id            varchar(64)  not null,
    owner_id          varchar(64),                          -- null = 주인 없음(보여도 되는 모두에게), 있으면 그 계정에게만
    scope             varchar(64),                          -- 결과를 좁히는 열린 값 (모듈은 뜻을 모른다)
    title             varchar(300) not null,
    body              text         not null,
    terms             tsvector     not null,
    source_updated_at timestamptz  not null,                -- 원본이 바뀐 시각 - 더 옛것은 덮어쓰지 않는다
    indexed_at        timestamptz  not null,                -- 이 줄을 쓴 시각 - 재색인 끝의 사라진 원본 정리가 쓴다
    constraint uq_search_documents_doc unique (doc_type, doc_id)
);
create index if not exists idx_search_documents_terms on search_documents using gin (terms);
create index if not exists idx_search_documents_owner on search_documents (owner_id);
create index if not exists idx_search_documents_type_indexed on search_documents (doc_type, indexed_at);

-- 종류별 재색인 진행. running 이고 updated_at 이 오래되면 멈춘 것으로 본다 (새 재색인을 받는다). finished_at 은 마지막으로 끝난 시각
create table if not exists search_rebuilds (
    doc_type    varchar(32) primary key,
    run_id      varchar(40) not null,
    running     boolean     not null,
    started_at  timestamptz not null,
    updated_at  timestamptz not null,
    finished_at timestamptz
);
