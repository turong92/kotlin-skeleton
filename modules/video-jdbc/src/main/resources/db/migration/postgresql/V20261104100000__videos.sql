-- modules:video-jdbc — 영상 (PostgreSQL). 설계: docs/modules/video.md
-- status: UPLOADING | UPLOADED | QUEUED | REMUXING | PLAYABLE | FAILED | DELETED (varchar — 열거값을 마이그레이션에 못 박지 않는다)
-- compat_status · ladder_status: NONE | SKIPPED | QUEUED | RUNNING | READY | FAILED (독립 트랙 — 실패해도 PLAYABLE 은 유지된다)
-- lane: REMUX | COMPAT | LADDER — 지금 집힌 차선(임대). lease_owner 는 일꾼 이름 — 토큰이 아니다
-- id 는 무작위 base64url 22자(주소에 쓴다) — 대소문자를 구분한다. owner_account_id 에 외래 키가 없다(계정 모듈에 기대지 않는다).
create table if not exists videos (
    id                      char(22)      primary key,
    owner_account_id        varchar(128)  not null,
    purpose                 varchar(32)   not null,
    visibility              varchar(8)    not null,
    status                  varchar(16)   not null,
    -- 올린 파일(비공개) · 멀티파트 id(QUEUED 가 되면 비운다)
    upload_key              varchar(255),
    upload_id               varchar(512),
    upload_bytes            bigint        not null default 0,
    last_upload_activity_at timestamptz   not null,
    -- 일꾼 ffprobe 결과
    src_container           varchar(64),
    src_codec               varchar(32),
    src_codec_string        varchar(64),
    src_width               int,
    src_height              int,
    src_rotation            int,
    src_duration_ms         bigint,
    src_fps                 numeric(8, 3),
    src_bitrate             bigint,
    src_audio_codec         varchar(32),
    -- 원본 단 (재인코딩 없는 조각 폴더)
    orig_key                varchar(255),
    orig_bytes              bigint,
    orig_sha256             varchar(64),
    -- 호환 단 트랙 — 원본이 호환이면 SKIPPED 이고 compat_key = orig_key
    compat_status           varchar(16)   not null default 'NONE',
    compat_key              varchar(255),
    compat_bytes            bigint,
    -- 사다리(HLS) 트랙
    ladder_status           varchar(16)   not null default 'NONE',
    ladder_build            varchar(32),
    ladder_bytes            bigint,
    ladder_rungs            text,
    poster_key              varchar(255),
    poster_w                int,
    poster_h                int,
    progress                smallint,
    attempts                int           not null default 0,
    lease_owner             varchar(64),
    lease_until             timestamptz,
    lane                    varchar(16),
    fail_code               varchar(64),
    fail_detail             varchar(500),
    created_at              timestamptz   not null,
    updated_at              timestamptz   not null
);
create index if not exists idx_videos_status_lease on videos (status, lease_until);
create index if not exists idx_videos_compat on videos (compat_status);
create index if not exists idx_videos_ladder on videos (ladder_status);
create index if not exists idx_videos_owner_purpose on videos (owner_account_id, purpose);

-- 일꾼 — 일꾼 전용 API 의 인증. 토큰은 SHA-256 해시만 저장한다(평문은 발급 응답에만 한 번).
-- lanes: 쉼표로 이은 허용 차선(REMUX,COMPAT,LADDER). 폐기는 revoked_at 만 채운다(행은 남긴다 — last_seen_at 으로 일꾼 부재를 본다)
create table if not exists video_workers (
    id            bigint generated by default as identity primary key,
    name          varchar(64)  not null,
    token_sha256  varchar(64)  not null,
    lanes         varchar(64)  not null,
    created_at    timestamptz  not null,
    last_seen_at  timestamptz,
    revoked_at    timestamptz
);
create unique index if not exists uk_video_workers_token on video_workers (token_sha256);

-- 클라우드 작업 깨우기 기록 — 동시 실행 상한 · 연달아 깨우기 억제 · 연속 실패 알림의 근거.
-- ok = 깨우기 호출이 받아들여졌나. execution 은 실행 이름(비밀이 아니다). error 는 예외 종류만(토큰 · 응답 본문 없음)
create table if not exists video_wake_runs (
    id        bigint generated by default as identity primary key,
    woke_at   timestamptz  not null,
    ok        boolean      not null,
    execution varchar(200),
    error     varchar(200)
);
create index if not exists ix_video_wake_runs_at on video_wake_runs (woke_at);
