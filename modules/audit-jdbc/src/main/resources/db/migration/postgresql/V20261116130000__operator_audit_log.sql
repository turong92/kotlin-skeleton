-- operator_audit_log (postgresql). 다른 브랜치의 미적용 마이그레이션에 기대지 않는다 (docs/schema-management.md)
-- modules:audit-jdbc — 운영자 행동 기록: 누가(actor_id) · 언제(occurred_at) · 무엇을(action) · 대상(target_type, target_id) · 결과(result) · 어디서(ip, user_agent).
-- **더하기만 한다** — 트리거가 막는 것: 고치기(항상), 지우기(기록한 지 30일이 안 된 줄 — 보관 기한 설정 skeleton.audit.retention 의 최솟값과 같다), 표 비우기(TRUNCATE).
-- 값은 id 만 — 이메일 · 이름 · 본문 · 토큰을 싣지 않는다(OperatorAction 의 규칙). ip · user_agent 는 개인정보라 보관 기한이 지나면 줄째 지워진다.
-- 새 표라서 옛 버전은 이 표를 모르고 그대로 돈다(expand).
create table if not exists operator_audit_log (
    id          bigint       generated by default as identity primary key,
    occurred_at timestamptz  not null,
    actor_id    varchar(64)  not null,
    action      varchar(100) not null,                    -- <모듈>.<대상>.<과거형>
    target_type varchar(64)  not null,
    target_id   varchar(128) not null,
    result      varchar(16)  not null,                    -- SUCCESS | DENIED | FAILED
    ip          varchar(64),
    user_agent  varchar(255),
    detail      text                                      -- OperatorAction.detail 의 JSON (문자열 맵)
);
create index if not exists idx_operator_audit_log_time on operator_audit_log (occurred_at);
create index if not exists idx_operator_audit_log_actor on operator_audit_log (actor_id, id);
create index if not exists idx_operator_audit_log_target on operator_audit_log (target_type, target_id, id);

create or replace function operator_audit_log_guard() returns trigger as $$
begin
    if tg_op = 'UPDATE' then
        raise exception 'operator_audit_log is append-only';
    end if;
    if old.occurred_at > now() - interval '30 days' then
        raise exception 'operator_audit_log is append-only: a line is deleted only after 30 days';
    end if;
    return old;
end;
$$ language plpgsql;

drop trigger if exists operator_audit_log_guard_trg on operator_audit_log;
create trigger operator_audit_log_guard_trg before update or delete on operator_audit_log for each row execute function operator_audit_log_guard();

create or replace function operator_audit_log_no_truncate() returns trigger as $$
begin
    raise exception 'operator_audit_log is append-only: no truncate';
end;
$$ language plpgsql;

drop trigger if exists operator_audit_log_no_truncate_trg on operator_audit_log;
create trigger operator_audit_log_no_truncate_trg before truncate on operator_audit_log for each statement execute function operator_audit_log_no_truncate();
