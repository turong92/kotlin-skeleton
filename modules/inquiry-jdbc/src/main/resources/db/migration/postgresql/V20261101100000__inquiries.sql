-- account_id 는 로그인해서 보냈을 때만 - 외래 키가 없다(계정 모듈에 기대지 않는다). 계정이 지워질 때 InquiryErasureListener 가 끊고 본문은 남긴다.
-- context 는 앱이 붙이는 선택 문자열(예: 어느 화면에서 왔는지) - 모듈은 뜻을 모른다.
create table if not exists inquiries (
    id           bigint generated by default as identity primary key,
    kind         varchar(16)   not null,   -- QUESTION | FEATURE | BUG | OTHER
    body         text          not null,
    reply_email  varchar(254),
    account_id   varchar(128),
    context      varchar(100),
    lang         varchar(16)   not null,
    status       varchar(8)    not null,   -- NEW | DONE
    created_at   timestamptz   not null,
    handled_at   timestamptz
);
create index if not exists idx_inquiries_status_created on inquiries (status, created_at);
create index if not exists idx_inquiries_account on inquiries (account_id);
